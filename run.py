"""Run everything: python run.py

Pulls prices, computes the spreads, builds the forward curves, runs the
mean-reversion check and writes figures/ plus results/latest.md.
"""
from __future__ import annotations

from pathlib import Path

import pandas as pd

from spreadtracker import backtest, curves, data, plots, signals, spreads

ROOT = Path(__file__).resolve().parent
RESULTS = ROOT / "results"


def md_table(df: pd.DataFrame, fmt: str = "{:,.2f}") -> str:
    def cell(v):
        if isinstance(v, (int,)) and not isinstance(v, bool):
            return str(v)
        if isinstance(v, float):
            return "" if pd.isna(v) else fmt.format(v)
        return str(v)
    head = "| " + " | ".join(str(c) for c in df.columns) + " |"
    sep = "|" + "|".join("---" for _ in df.columns) + "|"
    rows = ["| " + " | ".join(cell(v) for v in r) + " |" for r in df.itertuples(index=False)]
    return "\n".join([head, sep, *rows])


def main():
    RESULTS.mkdir(exist_ok=True)
    print("loading front-month prices ...")
    px = data.load_front()
    sp = spreads.all_spreads(px)
    sp.to_csv(RESULTS / "spreads.csv", float_format="%.4f")
    asof = sp.index[-1]

    # --- where are we now -------------------------------------------------
    rows = []
    for name in ["crack_321", "gasoline_crack", "distillate_crack", "brent_wti", "board_crush"]:
        s = sp[name].dropna()
        rows.append({
            "spread": spreads.LABELS[name],
            "last": s.iloc[-1],
            "1y avg": s.iloc[-252:].mean(),
            "z vs last year": signals.rolling_z(s).iloc[-1],
            "z vs same month, past years": signals.seasonal_z(s).iloc[-1],
            "5y percentile": signals.percentile_rank(s),
        })
    now = pd.DataFrame(rows)

    # --- curves -----------------------------------------------------------
    print("loading forward curves ...")
    cv = curves.snapshot()
    cm = pd.DataFrame({r: curves.curve_metrics(c) for r, c in cv.items()}).T
    cm.insert(0, "contract", cm.index)
    fwd = curves.forward_cracks(cv["CL"], cv["RB"], cv["HO"]) if {"CL", "RB", "HO"} <= set(cv) else None
    snap_dir = RESULTS / "curve_snapshots"
    snap_dir.mkdir(exist_ok=True)
    pd.DataFrame(cv).to_csv(snap_dir / f"{pd.Timestamp.today():%Y-%m-%d}.csv", float_format="%.4f")

    # --- mean reversion check --------------------------------------------
    print("running mean-reversion check ...")
    bt_rows, bt_daily, sens = [], {}, {}
    for name, cost in [("crack_321", 0.15), ("board_crush", 0.02)]:
        s = sp[name].dropna()
        z = signals.rolling_z(s, 252)
        trades, daily = backtest.run(s, z, entry=2.0, exit_=0.5, max_hold=60, cost=cost)
        trades.to_csv(RESULTS / f"trades_{name}.csv", index=False, float_format="%.4f")
        bt_daily[name] = daily
        bt_rows.append({"spread": spreads.LABELS[name], **backtest.summary(trades, daily)})
        sens[name] = backtest.sensitivity(s, signals.rolling_z, cost=cost)
    bt = pd.DataFrame(bt_rows)

    # --- figures ----------------------------------------------------------
    plots.spread_history(sp)
    plots.seasonality({k: signals.seasonal_profile(sp[k].dropna()) for k in ["gasoline_crack", "distillate_crack"]})
    plots.curves(cv, fwd)
    plots.backtest(bt_daily)

    # --- report -----------------------------------------------------------
    lines = [f"# Spread report, {asof:%d %b %Y}", "",
             "Generated by `python run.py`. Prices are Yahoo Finance front-month closes.", "",
             "## Where the spreads are", "", md_table(now), "",
             "## Curve structure (listed contract months)", "",
             md_table(cm[["contract", "front", "m1", "m1_m2", "m1_far", "far_months", "roll_yield_ann_pct", "structure"]]), ""]
    if "NG" in cv:
        ng = cv["NG"]
        h = [d for d in ng.index if d.month == 3]
        if h and h[0] + pd.offsets.MonthBegin(1) in ng.index:
            hj = ng[h[0]] - ng[h[0] + pd.offsets.MonthBegin(1)]
            lines += [f"Henry Hub March-April ({h[0]:%y}) spread: {hj:+.3f} $/MMBtu. "
                      "This is the end-of-winter spread, the market's price for running out of gas before injections start.", ""]
    if fwd is not None:
        f2 = fwd.copy(); f2.insert(0, "delivery", f2.index.strftime("%b-%y"))
        lines += ["## Forward cracks by delivery month ($/bbl)", "", md_table(f2), ""]
    lines += ["## Fading 2-sigma extremes (z vs trailing year, exit at 0.5, 60-day time stop)", "",
              "P&L is in spread units per one unit of spread, after a flat cost per round trip "
              "(0.15 $/bbl for the crack, 0.02 $/bu for crush).", "", md_table(bt), ""]
    for name, tab in sens.items():
        lines += [f"Sensitivity, {spreads.LABELS[name]}:", "", md_table(tab), ""]
    (RESULTS / "latest.md").write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
